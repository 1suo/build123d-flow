#!/usr/bin/env python3
"""Build the upstream Lib3MF Python binding and Emscripten side module wheel.

The generated Python binding and C++ library remain upstream Lib3MF 2.4.1.
The vendor patches adapt the Python platform suffix and forward the Emscripten
toolchain/emulator into upstream's nested bundled-libzip CMake configure. A
project-scoped CMake include enables shared-library support for the Lib3MF
target only, allowing Emscripten to emit the ctypes-loaded SIDE_MODULE.
"""
from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import json
import shutil
import subprocess
import tempfile
import zipfile
from pathlib import Path

VERSION = "2.4.1"
SOURCE_TAG = "v2.4.1"
PYTHON_TAG = "cp314-cp314"
PLATFORM_TAG = "pyemscripten_2026_0_wasm32"
EMSCRIPTEN_VERSION = "5.0.3"
CMAKE_VERSION = "3.31.10"
WHEEL_NAME = f"lib3mf-{VERSION}-{PYTHON_TAG}-{PLATFORM_TAG}.whl"


def run(command: list[str], cwd: Path | None = None) -> None:
    print("+", " ".join(str(part) for part in command), flush=True)
    subprocess.run(command, cwd=cwd, check=True)


def patch_platform_suffix(source: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    text = source.read_text(encoding="utf-8")
    original = (
        "\t\telif platform.system() == 'Darwin':\n"
        "\t\t\tending = 'dylib'\n"
        "\t\telse:"
    )
    replacement = (
        "\t\telif platform.system() == 'Darwin':\n"
        "\t\t\tending = 'dylib'\n"
        "\t\telif platform.system() == 'Emscripten':\n"
        "\t\t\tending = 'so'\n"
        "\t\telse:"
    )
    if text.count(original) != 1:
        raise RuntimeError("Expected exactly one upstream Lib3MF platform suffix block")
    destination.write_text(text.replace(original, replacement), encoding="utf-8")


def patch_nested_libzip_configure(source: Path) -> None:
    cmake_file = source / "CMakeLists.txt"
    text = cmake_file.read_text(encoding="utf-8")
    configure_anchor = (
        '            "-S" "${CMAKE_CURRENT_SOURCE_DIR}/submodules/libzip" '
        '"-B" "${CMAKE_CURRENT_BINARY_DIR}/libzip"'
    )
    configure_replacement = (
        '            "-DCMAKE_TOOLCHAIN_FILE=${CMAKE_TOOLCHAIN_FILE}"\n'
        '            "-DCMAKE_CROSSCOMPILING_EMULATOR=${CMAKE_CROSSCOMPILING_EMULATOR}"\n'
        + configure_anchor
    )
    if text.count(configure_anchor) != 1:
        raise RuntimeError("Expected exactly one bundled libzip configure invocation")
    text = text.replace(configure_anchor, configure_replacement)
    result_anchor = '    MESSAGE( STATUS "CMD_ERROR:" ${CMD_ERROR})'
    result_replacement = (
        '    if(NOT CMD_ERROR EQUAL 0)\n'
        '        message(FATAL_ERROR "Failed to configure bundled libzip for the active toolchain: ${CMD_ERROR}")\n'
        '    endif()'
    )
    if text.count(result_anchor) != 1:
        raise RuntimeError("Expected exactly one bundled libzip configure result")
    cmake_file.write_text(text.replace(result_anchor, result_replacement), encoding="utf-8")


def record_digest(data: bytes) -> str:
    return "sha256=" + base64.urlsafe_b64encode(hashlib.sha256(data).digest()).decode("ascii").rstrip("=")


def make_wheel(source_root: Path, library: Path, wheelhouse: Path) -> Path:
    package_root = source_root / "package" / "lib3mf"
    package_root.mkdir(parents=True)
    binding = source_root / "Autogenerated" / "Bindings" / "Python" / "Lib3MF.py"
    if not binding.is_file():
        raise RuntimeError(f"Missing upstream generated Python binding: {binding}")
    patch_platform_suffix(binding, package_root / "Lib3MF.py")
    (package_root / "__init__.py").write_text(
        "from . import Lib3MF as Lib3MF\n",
        encoding="utf-8",
    )
    shutil.copy2(library, package_root / "lib3mf.so")

    dist_info = source_root / "package" / f"lib3mf-{VERSION}.dist-info"
    dist_info.mkdir()
    (dist_info / "METADATA").write_text(
        "Metadata-Version: 2.1\n"
        "Name: lib3mf\n"
        f"Version: {VERSION}\n"
        "Summary: Upstream 3MF Consortium Python bindings for Lib3MF\n"
        "License: BSD-2-Clause\n"
        "Requires-Python: >=3.11\n",
        encoding="utf-8",
    )
    (dist_info / "WHEEL").write_text(
        "Wheel-Version: 1.0\n"
        "Generator: build123d-flow-lib3mf-wasm-builder\n"
        "Root-Is-Purelib: false\n"
        f"Tag: {PYTHON_TAG}-{PLATFORM_TAG}\n",
        encoding="utf-8",
    )

    wheelhouse.mkdir(parents=True, exist_ok=True)
    wheel_path = wheelhouse / WHEEL_NAME
    entries: list[tuple[str, bytes]] = []
    for path in sorted((source_root / "package").rglob("*")):
        if path.is_file() and path.name != "RECORD":
            entries.append((path.relative_to(source_root / "package").as_posix(), path.read_bytes()))

    record_rows = [
        (name, record_digest(data), str(len(data)))
        for name, data in entries
    ]
    record_name = f"lib3mf-{VERSION}.dist-info/RECORD"
    record_rows.append((record_name, "", ""))
    from io import StringIO
    record_stream = StringIO(newline="")
    writer = csv.writer(record_stream, lineterminator="\n")
    writer.writerows(record_rows)
    entries.append((record_name, record_stream.getvalue().encode("utf-8")))

    with zipfile.ZipFile(wheel_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in entries:
            archive.writestr(name, data)

    return wheel_path


def register_wheel(wheelhouse: Path, wheel_path: Path) -> None:
    manifest_path = wheelhouse / "manifest.json"
    if not manifest_path.is_file():
        raise RuntimeError(f"Pyodide wheel manifest must be staged first: {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest = [item for item in manifest if item.get("name", "").lower().replace("_", "-") != "lib3mf"]
    manifest.append({
        "name": "lib3mf",
        "version": VERSION,
        "filename": WHEEL_NAME,
        "sha256": hashlib.sha256(wheel_path.read_bytes()).hexdigest(),
    })
    manifest.sort(key=lambda item: item["name"].lower())
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("wheelhouse", type=Path)
    args = parser.parse_args()
    args.wheelhouse.mkdir(parents=True, exist_ok=True)
    cached_wheel = args.wheelhouse / WHEEL_NAME
    if cached_wheel.is_file():
        register_wheel(args.wheelhouse, cached_wheel)
        print(f"Registered cached {cached_wheel}", flush=True)
        return

    emcc_version = subprocess.check_output(["emcc", "--version"], text=True)
    if EMSCRIPTEN_VERSION not in emcc_version:
        raise RuntimeError(
            "Expected Emscripten {}, got: {}".format(EMSCRIPTEN_VERSION, emcc_version.splitlines()[0])
        )
    cmake_version = subprocess.check_output(["cmake", "--version"], text=True).split()[2]
    if cmake_version != CMAKE_VERSION:
        raise RuntimeError("Expected CMake {}, got {}".format(CMAKE_VERSION, cmake_version))
    print("Using Emscripten {} and CMake {}".format(EMSCRIPTEN_VERSION, CMAKE_VERSION), flush=True)

    with tempfile.TemporaryDirectory(prefix="build123d-flow-lib3mf-") as temporary:
        root = Path(temporary)
        source = root / "lib3mf"
        build = root / "build"
        run([
            "git", "clone", "--depth", "1", "--branch", SOURCE_TAG,
            "--recurse-submodules", "--shallow-submodules",
            "https://github.com/3MFConsortium/lib3mf.git", str(source),
        ])
        patch_nested_libzip_configure(source)
        shared_support = root / "enable_lib3mf_side_module.cmake"
        shared_support.write_text(
            "set_property(GLOBAL PROPERTY TARGET_SUPPORTS_SHARED_LIBS TRUE)\n",
            encoding="utf-8",
        )
        common_flags = "-O2 -fwasm-exceptions -sSUPPORT_LONGJMP=wasm"
        run([
            "emcmake", "cmake", "-S", str(source), "-B", str(build), "-G", "Ninja",
            f"-DCMAKE_PROJECT_lib3mf_INCLUDE={shared_support}",
            "-DCMAKE_BUILD_TYPE=Release",
            "-DLIB3MF_TESTS=OFF",
            "-DSTRIP_BINARIES=OFF",
            "-DUSE_INCLUDED_ZLIB=ON",
            "-DUSE_INCLUDED_LIBZIP=ON",
            "-DUSE_PLATFORM_UUID=OFF",
            f"-DCMAKE_C_FLAGS={common_flags}",
            f"-DCMAKE_CXX_FLAGS=-std=c++17 {common_flags}",
            f"-DCMAKE_SHARED_LINKER_FLAGS=-sSIDE_MODULE=1 {common_flags}",
        ])
        run(["cmake", "--build", str(build), "--parallel", "4"])
        candidates = list(build.rglob("lib3mf.so"))
        if not candidates:
            candidates = list(build.rglob("lib3mf.so.*"))
        if not candidates:
            raise RuntimeError("Lib3MF build produced no shared library")
        library = candidates[0]
        wasm = library.read_bytes()
        if not wasm.startswith(b"\x00asm") or b"dylink.0" not in wasm:
            raise RuntimeError(f"Lib3MF output is not an Emscripten side module: {library}")
        wheel = make_wheel(source, library, args.wheelhouse)
        register_wheel(args.wheelhouse, wheel)
        print(f"Built {wheel} ({wheel.stat().st_size:,} bytes)", flush=True)


if __name__ == "__main__":
    main()
