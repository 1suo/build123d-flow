import json
import runpy
import tempfile
import unittest
import zipfile
from pathlib import Path

BUILDER = runpy.run_path(str(Path(__file__).parents[1] / "scripts" / "build_lib3mf_wasm.py"))


class Lib3MFWasmPackagingTests(unittest.TestCase):
    def test_nested_libzip_configure_inherits_emscripten_toolchain(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory)
            cmake_file = source / "CMakeLists.txt"
            cmake_file.write_text(
                'execute_process(\n'
                '  COMMAND ${CMAKE_COMMAND} "-DBUILD_EXAMPLES=OFF"\n'
                '            "-S" "${CMAKE_CURRENT_SOURCE_DIR}/submodules/libzip" "-B" "${CMAKE_CURRENT_BINARY_DIR}/libzip"\n'
                '      RESULT_VARIABLE CMD_ERROR\n'
                '      OUTPUT_QUIET)\n'
                '    MESSAGE( STATUS "CMD_ERROR:" ${CMD_ERROR})\n',
                encoding="utf-8",
            )
            BUILDER["patch_nested_libzip_configure"](source)
            patched = cmake_file.read_text(encoding="utf-8")

        self.assertIn('-DCMAKE_TOOLCHAIN_FILE=${CMAKE_TOOLCHAIN_FILE}', patched)
        self.assertIn('-DCMAKE_CROSSCOMPILING_EMULATOR=${CMAKE_CROSSCOMPILING_EMULATOR}', patched)
        self.assertIn("message(FATAL_ERROR", patched)

    def test_upstream_python_binding_gets_only_emscripten_suffix_patch(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory) / "Lib3MF.py"
            destination = Path(directory) / "package" / "Lib3MF.py"
            destination.parent.mkdir(parents=True)
            source.write_text(
                "\t\telif platform.system() == 'Darwin':\n"
                "\t\t\tending = 'dylib'\n"
                "\t\telse:\n"
                "\t\t\traise ELib3MFException(ErrorCodes.COULDNOTLOADLIBRARY)\n",
                encoding="utf-8",
            )
            BUILDER["patch_platform_suffix"](source, destination)
            patched = destination.read_text(encoding="utf-8")

        self.assertIn("platform.system() == 'Emscripten'", patched)
        self.assertIn("ending = 'so'", patched)
        self.assertIn("platform.system() == 'Darwin'", patched)

    def test_wheel_contains_upstream_binding_and_side_module(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            binding = root / "Autogenerated" / "Bindings" / "Python" / "Lib3MF.py"
            binding.parent.mkdir(parents=True)
            binding.write_text(
                "\t\telif platform.system() == 'Darwin':\n"
                "\t\t\tending = 'dylib'\n"
                "\t\telse:\n"
                "\t\t\traise ELib3MFException(ErrorCodes.COULDNOTLOADLIBRARY)\n",
                encoding="utf-8",
            )
            library = root / "lib3mf.so"
            library.write_bytes(b"\x00asm\x01\x00\x00\x00dylink.0")
            wheelhouse = root / "wheels"
            wheelhouse.mkdir()
            (wheelhouse / "manifest.json").write_text("[]", encoding="utf-8")

            wheel = BUILDER["make_wheel"](root, library, wheelhouse)
            BUILDER["register_wheel"](wheelhouse, wheel)

            with zipfile.ZipFile(wheel) as archive:
                names = set(archive.namelist())
                binding_text = archive.read("lib3mf/Lib3MF.py").decode("utf-8")
                self.assertEqual(archive.read("lib3mf/lib3mf.so"), library.read_bytes())
            manifest = json.loads((wheelhouse / "manifest.json").read_text(encoding="utf-8"))

        self.assertIn("lib3mf/Lib3MF.py", names)
        self.assertIn("lib3mf/__init__.py", names)
        self.assertIn("lib3mf/lib3mf.so", names)
        self.assertIn("platform.system() == 'Emscripten'", binding_text)
        self.assertEqual(len(manifest), 1)
        self.assertEqual(manifest[0]["name"], "lib3mf")
        self.assertEqual(manifest[0]["version"], "2.4.1")


if __name__ == "__main__":
    unittest.main()
